"""
pages/5_AI_Insights.py

Renders the natural-language insights generated by
analytics/insights.py. No external AI API is required -- every
insight is a Pandas/NumPy computation turned into a sentence.
"""

import streamlit as st

from analytics.insights import generate_all_insights
from auth.session import current_user_id, require_login
from database.queries import get_coding_logs_df, get_study_sessions_df

st.set_page_config(page_title="AI Insights - LifeOS", page_icon="🧠", layout="wide")
require_login()

user_id = current_user_id()
st.title("AI Insights")
st.caption("Data-driven observations about your study and coding patterns.")

study_df = get_study_sessions_df(user_id)
coding_df = get_coding_logs_df(user_id)

insights = generate_all_insights(study_df, coding_df)

if not insights:
    st.info(
        "**Not enough data yet.**\n\n"
        "Log a few more study sessions or solved problems and check back -- "
        "insights need some history to work with."
    )
else:
    for insight in insights:
        with st.container(border=True):
            st.markdown(f"### {insight['icon']} {insight['title']}")
            st.write(insight["body"])
